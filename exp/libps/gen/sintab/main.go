// Command sintab writes the library's tables of sines and square roots,
// gtetab.go: the quarter turn from 0 to 1024 in 4096ths of a turn, each
// 4096 times the sine rounded to the nearest, and the square roots of 64
// to 255 over 64, each 4096 times the root rounded down, both in 4.12
// fixed point.
package main

import (
	"bytes"
	"fmt"
	"math"
	"os"
)

func main() {
	var b bytes.Buffer
	b.WriteString("//go:build yaroze\n\n")
	b.WriteString("package libps\n\n")
	b.WriteString("// Code generated by gen/sintab; DO NOT EDIT.\n\n")
	b.WriteString("// sinTable is a quarter turn of sines in 4.12, one for each of the 1025\n")
	b.WriteString("// angles from 0 to 1024, in 4096ths of a turn, rounded to the nearest,\n")
	b.WriteString("// which rsin, rcos and the rotation matrices fold the other quarters\n")
	b.WriteString("// onto.\n")
	b.WriteString("var sinTable = [1025]int16{\n")
	for i := 0; i <= 1024; i++ {
		if i%16 == 0 {
			b.WriteString("\t")
		}
		v := math.Floor(4096*math.Sin(float64(i)*2*math.Pi/4096) + 0.5)
		fmt.Fprintf(&b, "%d,", int(v))
		if i%16 == 15 || i == 1024 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// sqrtTable is the square roots of 64 to 255 over 64, in 4.12, rounded\n")
	b.WriteString("// down: what SquareRoot0 scales to a number's leading byte.\n")
	b.WriteString("var sqrtTable = [192]int16{\n")
	for n := 64; n < 256; n++ {
		if n%16 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(&b, "%d,", int(math.Floor(4096*math.Sqrt(float64(n)/64))))
		if n%16 == 15 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("}\n")
	if err := os.WriteFile("gtetab.go", b.Bytes(), 0o666); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

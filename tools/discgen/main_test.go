package main

import (
	"os"
	"path/filepath"
	"testing"

	"go.chrisrx.dev/x/assert"
)

func TestIdent(t *testing.T) {
	for rel, want := range map[string]string{
		"CUBE.TMD":      "cubeTMD",
		"GIULI_BD.TIM":  "giuliBdTIM",
		"sound/STD0.VH": "soundStd0VH",
		"0.VB":          "file0VB",
		"README":        "readme",
	} {
		name, _ := ident(rel)
		assert.Equal(t, want, name, rel)
	}
}

func TestGenerate(t *testing.T) {
	dir := t.TempDir()
	assert.NoError(t, os.MkdirAll(filepath.Join(dir, "data", "sound"), 0o755))
	for name, size := range map[string]int{
		"data/CUBE.TIM":      4128,
		"data/CUBE.TMD":      2048,
		"data/sound/STD0.VH": 1,
		"data/.hidden":       10,
	} {
		assert.NoError(t, os.WriteFile(filepath.Join(dir, name), make([]byte, size), 0o644))
	}
	files, err := scan(filepath.Join(dir, "data"))
	files = assert.Ok(t, files, err)

	src, err := generate(options{Package: "main", Dir: "data", Root: "DATA", Files: "files"}, files)
	src = assert.Ok(t, src, err)
	assert.Equal(t, `// Code generated by discgen. DO NOT EDIT.

package main

import (
	"go.chrisrx.dev/psx/disc"
)

// The files under data, placed on the disc under DATA.
var (
	cubeTIM     = disc.Register("DATA/CUBE.TIM", "data/CUBE.TIM")
	cubeTMD     = disc.Register("DATA/CUBE.TMD", "data/CUBE.TMD")
	soundStd0VH = disc.Register("DATA/SOUND/STD0.VH", "data/sound/STD0.VH")
)

// files is every file above, in the order disc.LoadAll reads them.
var files = []*disc.File{
	&cubeTIM,
	&cubeTMD,
	&soundStd0VH,
}
`, string(src))

	src, err = generate(options{Package: "main", Dir: "data", Root: "DATA", Files: "files", Into: true}, files)
	src = assert.Ok(t, src, err)
	assert.Equal(t, `// Code generated by discgen. DO NOT EDIT.

package main

import (
	"go.chrisrx.dev/psx/disc"
	"go.chrisrx.dev/psx/yaroze"
)

// The files under data, placed on the disc under DATA, each with the memory
// it is read into: its length rounded up to whole 2048-byte sectors, as
// the drive delivers them.
var (
	cubeTIMData [1536]uint32 // 4128 bytes
	cubeTIMFile = disc.Register("DATA/CUBE.TIM", "data/CUBE.TIM").Into(cubeTIMData[:])
	cubeTIM     = yaroze.TIM(cubeTIMData[:])

	cubeTMDData [512]uint32 // 2048 bytes
	cubeTMDFile = disc.Register("DATA/CUBE.TMD", "data/CUBE.TMD").Into(cubeTMDData[:])
	cubeTMD     = yaroze.TMD(cubeTMDData[:])

	soundStd0VHData [512]uint32 // 1 bytes
	soundStd0VHFile = disc.Register("DATA/SOUND/STD0.VH", "data/sound/STD0.VH").Into(soundStd0VHData[:])
)

// files is every file above, in the order disc.LoadAll reads them.
var files = []*disc.File{
	&cubeTIMFile,
	&cubeTMDFile,
	&soundStd0VHFile,
}
`, string(src))
}

func TestGenerateRejectsClashes(t *testing.T) {
	_, err := generate(options{Package: "main", Dir: "data", Root: "DATA", Files: "files"}, []entry{
		{rel: "a-b.VH", size: 1},
		{rel: "a_b.VH", size: 1},
	})
	assert.Error(t, "a-b.VH and a_b.VH would both be named aBVH", err)
}

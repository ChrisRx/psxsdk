package main

// The screen's font: the printable ASCII characters, 0x20 to 0x7e, each
// seven rows of five dots drawn in an 8 by 8 cell. The space to the
// underscore are the clean library's (internal/libps/gen/font), and the
// rest are drawn to match.

// fontFirst is the first character the font has, and fontCount how many.
const (
	fontFirst = 0x20
	fontCount = 0x7f - fontFirst
)

// fontRows is the font, a row a byte with the leftmost dot in bit 4,
// filled in from fontArt by init.
var fontRows [fontCount][7]byte

func init() {
	g, row, col := 0, 0, 0
	for i := range len(fontArt) {
		switch fontArt[i] {
		case '#':
			fontRows[g][row] |= 0x10 >> col
			col++
		case '.':
			col++
		case '\n':
			if col > 0 {
				row++
				col = 0
			} else if row > 0 {
				g++
				row = 0
			}
		}
	}
}


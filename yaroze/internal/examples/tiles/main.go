func main() {
	screen.Open()
	text = screen.Font(8, 8, 304, 40, 200)

	if f := disc.LoadAll(300); f != nil {
		for range screen.Frames() {
			text.Print("could not read ").Print(f.Name)
		}
	}
	image := yaroze.LoadTIM(bgTIM.Data())

	// Sixteen cells, eight across and two down, from the image's corner.
	for i := range cells {
		cells[i] = image.Cell(i%8*tileSize, i/8*tileSize)
	}
	bg.Init(&screen, &tiles)

	for frame := range screen.Frames() {
		dx, dy := direction(yaroze.PadButtons(0))
		x, y := bg.Scroll()
		w, h := bg.Size()
		x = max(0, min(x+dx*speed, mapW*tileSize-w))
		y = max(0, min(y+dy*speed, mapH*tileSize-h))
		bg.ScrollTo(x, y)
		bg.Draw(frame, 1)

		text.Print("~c000SCROLL ").Int(x).Print(",").Int(y).
			Print(" OF ").Int(mapW * tileSize).Print(" BY ").Int(mapH * tileSize).Print("\n")
	}
}

// direction is which way the directions push, -1, 0 or 1 each way.
func direction(held yaroze.Buttons) (dx, dy int) {
	if held.Has(yaroze.Left) {
		dx--
	}
	if held.Has(yaroze.Right) {
		dx++
	}
	if held.Has(yaroze.Up) {
		dy--
	}
	if held.Has(yaroze.Down) {
		dy++
	}
	return dx, dy
}

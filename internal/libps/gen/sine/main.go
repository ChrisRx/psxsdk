// Command sine writes sinedata.go, the declaration of the clean library's sine
// table, and prints the table for the target's assembly: the sine of each angle of the
// first quarter turn, 0 to 1024 in 4096ths of a turn, in 4.12 fixed point, rounded to
// nearest. The other quarters fold onto it by symmetry.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"os"
)

func main() {
	var b bytes.Buffer
	b.WriteString("//go:build yaroze\n\n")
	b.WriteString("package libps\n\n")
	b.WriteString("// Code generated by gen/sine; DO NOT EDIT.\n\n")
	b.WriteString("// sineTable is the sine of each angle of the first quarter turn, 0 to\n")
	b.WriteString("// 1024 in 4096ths of a turn, in 4.12 fixed point. It lives with RotMatrix and\n")
	b.WriteString("// the others that read it, in the target's assembly (playstation-yaroze-clean.S),\n")
	b.WriteString("// which gen/sine prints.\n//\n//go:extern libps_sine_table\n")
	b.WriteString("var sineTable [1025]int16\n")
	for a := 0; a <= 1024; a++ {
		v := math.Floor(4096*math.Sin(2*math.Pi*float64(a)/4096) + 0.5)
		if a%16 == 0 {
			fmt.Printf("\n\t.hword %d", int(v))
		} else {
			fmt.Printf(", %d", int(v))
		}
	}
	fmt.Println()
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "sine:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("sinedata.go", src, 0o666); err != nil {
		fmt.Fprintln(os.Stderr, "sine:", err)
		os.Exit(1)
	}
}

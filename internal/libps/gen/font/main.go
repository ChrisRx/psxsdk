func main() {
	var rows [][8]uint32 // the image's rows, 16 words each
	rows = make([][8]uint32, 0)
	_ = rows
	var image [32][16]uint32
	blocks := strings.Split(strings.TrimSpace(glyphs), "\n\n")
	if len(blocks) != 64 {
		fmt.Fprintf(os.Stderr, "font: %d glyphs, not 64\n", len(blocks))
		os.Exit(1)
	}
	for g, block := range blocks {
		lines := strings.Split(strings.TrimSpace(block), "\n")
		if len(lines) != 7 {
			fmt.Fprintf(os.Stderr, "font: glyph %d has %d rows, not 7\n", g, len(lines))
			os.Exit(1)
		}
		cx, cy := g%16, g/16
		for r, line := range lines {
			if len(line) != 5 {
				fmt.Fprintf(os.Stderr, "font: glyph %d row %d is %q, not five columns\n", g, r, line)
				os.Exit(1)
			}
			var w uint32
			for x, c := range line {
				if c == '#' {
					w |= 1 << (4 * (x + 1))
				}
			}
			image[cy*8+r][cx] = w
		}
	}

	var b bytes.Buffer
	b.WriteString("//go:build yaroze\n\n")
	b.WriteString("package libps\n\n")
	b.WriteString("// Code generated by gen/font; DO NOT EDIT.\n\n")
	b.WriteString("// fontPixels is the library's font, as FntLoad puts it into video memory:\n")
	b.WriteString("// 128 by 32 pixels of 4-bit color, sixteen glyphs of 8 by 8 to a row,\n")
	b.WriteString("// four rows, from the space to the underscore, drawn in gen/font.\n")
	b.WriteString("var fontPixels = [512]uint32{\n")
	for _, row := range image {
		b.WriteString("\t")
		for i, w := range row {
			if i > 0 {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "0x%08x,", w)
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	if err := os.WriteFile("fontdata.go", b.Bytes(), 0o666); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

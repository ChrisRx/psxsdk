// Command mkfiles writes the cdlimits probe's files.go, the registrations
// of every file its disc carries and the index of each group, into the
// directory given (the probe's), and files/track.raw there, five seconds of
// silence the disc build records as a CD audio track (--audio). Every file
// is the same 100-byte asset: a file is told apart by where the disc build
// placed it.
//
// The layout, from the ISO 9660 writer's sorting (directories and files
// each in identifier order, the path table breadth first) and its record
// sizes (33 bytes plus the identifier, padded even, plus the 14-byte XA
// area; "." and ".." are 48 bytes each; a record does not cross a sector):
//
//   - Root directories, in path table order after the root: the 16- and
//     24-character names, B (a canary after them), F, G, L, N, O40, P28 to
//     P40 and Q. Then, at level 2, G's 41 directories and Q's 300
//     directories 000 to 299: the path table's entry 128 is Q/068.
//     Q's own listing holds "." and ".." and 000 to 038 in its first
//     sector.
//   - F holds 45 files: 0 to 9, A to Z and _ (50-byte records) and _A to
//     _H (52 bytes). The first sector of its listing holds "." and "..",
//     the 37 one-character names and _A, 40 records in 1998 bytes; _B to
//     _H lie in the second sector.
//   - G holds 41 directories: 0 to 9, A to Z and _ (48-byte records) and
//     _A to _D (50 bytes), each with a file X.BIN. The first sector of
//     its listing holds 42 records, "." and ".." through _C (2022 bytes),
//     as many as a sector can hold; _D lies in the second.
//   - L holds files whose identifiers (version included) are 7, 15, 16,
//     17, 20 and 26 bytes long, each long one followed in name order by a
//     short one.
//   - Each Pnn holds A and a file whose identifier is nn bytes long, its
//     last record; O40 holds A, a 40-byte identifier and ZZ after it; N
//     holds A, B and C.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// pLengths are the identifier lengths of the P directories' long names.
var pLengths = []int{28, 30, 31, 32, 33, 34, 36, 40}

// longName is an identifier of n bytes with its ";1": Z, digits, ".BIN".
func longName(n int) string {
	s := "Z"
	for i := 2; len(s) < n-6; i++ {
		s += string(rune('0' + i%10))
	}
	return s + ".BIN"
}

func main() {
	dir := os.Args[1]
	var b strings.Builder
	b.WriteString("// Code generated by mkfiles; DO NOT EDIT.\n\npackage main\n\nimport \"go.chrisrx.dev/psx/disc\"\n\n")
	var names []string
	var consts []string
	group := func(name string) {
		consts = append(consts, fmt.Sprintf("\t%s = %d", name, len(names)))
	}
	add := func(p string) {
		names = append(names, p)
	}
	group("dirA16")
	add("ABCDEFGHIJKLMNOP/X.BIN")
	group("dirA24")
	add("ABCDEFGHIJKLMNOPQRSTUVWX/X.BIN")
	group("dirB")
	add("B/X.BIN")
	group("qFirst")
	for i := range 300 {
		add(fmt.Sprintf("Q/%03d/X.BIN", i))
	}
	group("fFirst")
	for _, n := range shortNames {
		add("F/" + n)
	}
	for c := 'A'; c <= 'H'; c++ {
		add("F/_" + string(c))
	}
	group("gFirst")
	for _, n := range shortNames {
		add("G/" + n + "/X.BIN")
	}
	for c := 'A'; c <= 'D'; c++ {
		add("G/_" + string(c) + "/X.BIN")
	}
	group("lFirst")
	for _, n := range longNames {
		add("L/" + n)
	}
	group("pFirst")
	for _, n := range pLengths {
		add(fmt.Sprintf("P%d/A", n))
		add(fmt.Sprintf("P%d/%s", n, longName(n)))
	}
	group("nFirst")
	add("N/A")
	add("N/B")
	add("N/C")
	group("oFirst")
	add("O40/A")
	add("O40/" + longName(40))
	add("O40/ZZ")
	group("nFiles")
	b.WriteString("const (\n" + strings.Join(consts, "\n") + "\n)\n\nvar (\n")
	for i, p := range names {
		fmt.Fprintf(&b, "\tf%d = disc.Register(%q, \"assets/X.BIN\")\n", i, p)
	}
	b.WriteString(")\n\n// files are the registrations, in the order above, and paths their names.\nvar files = [...]*disc.File{\n")
	for i := range names {
		fmt.Fprintf(&b, "\t&f%d,\n", i)
	}
	b.WriteString("}\n\nvar paths = [...]string{\n")
	for _, p := range names {
		fmt.Fprintf(&b, "\t%q,\n", p)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "files.go"), src, 0o644); err != nil {
		panic(err)
	}
	os.MkdirAll(filepath.Join(dir, "files"), 0o755)
	if err := os.WriteFile(filepath.Join(dir, "files", "track.raw"), make([]byte, 5*75*2352), 0o644); err != nil {
		panic(err)
	}
}

// shortNames are the 37 one-character names, in identifier order.
var shortNames = func() []string {
	var s []string
	for c := '0'; c <= '9'; c++ {
		s = append(s, string(c))
	}
	for c := 'A'; c <= 'Z'; c++ {
		s = append(s, string(c))
	}
	return append(s, "_")
}()

// longNames are L's files; with ";1" their identifiers are 7, 15, 7, 16,
// 7, 17, 7, 20, 7, 26 and 7 bytes.
var longNames = []string{
	"A.BIN",
	"B23456789.BIN",
	"C.BIN",
	"D234567890.BIN",
	"E.BIN",
	"F2345678901.BIN",
	"G.BIN",
	"H2345678901234.BIN",
	"I.BIN",
	"J2345678901234567890.BIN",
	"K.BIN",
}

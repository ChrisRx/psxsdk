// Command mkfiles writes the cdmore probe's files.go, the registrations of
// every file its disc carries and the index of each group, into the
// directory given (the probe's), and files/track.raw there, five seconds of
// silence the disc build records as a CD audio track (--audio). Every file
// is the same 100-byte asset: a file is told apart by where the disc build
// placed it.
//
// The disc is built with --no-xa, so that a record is 33 bytes plus its
// identifier, padded even, with no 14-byte XA area after it: the shortest
// records ISO 9660 allows, 34 bytes for a one-character directory name and
// 36 for a two-character one, where cdlimits' records were 48 and more and
// a sector showed 42 at most. "." and ".." are 34 bytes each.
//
//   - R holds 60 directories, each with a file X.BIN: the 37 one-character
//     names (0 to 9, A to Z and _) and _0 to _9 and _A to _M. Its listing's
//     first sector holds "." and ".." and the first 57 of them, 59 records
//     in 2046 bytes, as many as a sector can show; _K, _L and _M lie in
//     the second sector.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	dir := os.Args[1]
	var b strings.Builder
	b.WriteString("// Code generated by mkfiles; DO NOT EDIT.\n\npackage main\n\nimport \"go.chrisrx.dev/psx/disc\"\n\n")
	var names []string
	var consts []string
	group := func(name string) {
		consts = append(consts, fmt.Sprintf("\t%s = %d", name, len(names)))
	}
	add := func(p string) {
		names = append(names, p)
	}
	group("rFirst")
	for _, n := range rNames {
		add("R/" + n + "/X.BIN")
	}
	group("nFiles")
	b.WriteString("const (\n" + strings.Join(consts, "\n") + "\n)\n\nvar (\n")
	for i, p := range names {
		fmt.Fprintf(&b, "\tf%d = disc.Register(%q, \"assets/X.BIN\")\n", i, p)
	}
	b.WriteString(")\n\n// files are the registrations, in the order above, and paths their names.\nvar files = [...]*disc.File{\n")
	for i := range names {
		fmt.Fprintf(&b, "\t&f%d,\n", i)
	}
	b.WriteString("}\n\nvar paths = [...]string{\n")
	for _, p := range names {
		fmt.Fprintf(&b, "\t%q,\n", p)
	}
	b.WriteString("}\n\n// rNames are R's directories, in record order.\nvar rNames = [...]string{\n")
	for _, n := range rNames {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "files.go"), src, 0o644); err != nil {
		panic(err)
	}
	os.MkdirAll(filepath.Join(dir, "files"), 0o755)
	if err := os.WriteFile(filepath.Join(dir, "files", "track.raw"), make([]byte, 5*75*2352), 0o644); err != nil {
		panic(err)
	}
}

// oneChar are the 37 one-character names, in identifier order.
var oneChar = func() []string {
	var s []string
	for c := '0'; c <= '9'; c++ {
		s = append(s, string(c))
	}
	for c := 'A'; c <= 'Z'; c++ {
		s = append(s, string(c))
	}
	return append(s, "_")
}()

// rNames are R's 60 directories in record order: the one-character names,
// then _0 to _9 and _A to _M.
var rNames = func() []string {
	s := append([]string{}, oneChar...)
	for c := '0'; c <= '9'; c++ {
		s = append(s, "_"+string(c))
	}
	for c := 'A'; c <= 'M'; c++ {
		s = append(s, "_"+string(c))
	}
	return s
}()

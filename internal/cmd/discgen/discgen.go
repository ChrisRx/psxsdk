// Package discgen writes the Go declarations for a program's data files:
// for each file under a directory, the disc.File that registers it with
// mkdisc, and a slice of every File for disc.LoadAll, which reads each
// into memory it allocates. The sources the converters read, which lie in
// the same directory, are left off the disc: a picture, model, sound or
// score by its extension, and any file a go:generate line of the package
// reads.
//
// It is the discgen command, and yaroze's generate command, meant for
// go:generate in the program's package:
//
//	//go:generate go run go.chrisrx.dev/psx/tools/discgen assets
//
// which for assets/CUBE.TMD and assets/CUBE.TIM writes zz_generated.disc.go
// with
//
//	cubeTIM = disc.Register("ASSETS/CUBE.TIM", "assets/CUBE.TIM")
//	cubeTMD = disc.Register("ASSETS/CUBE.TMD", "assets/CUBE.TMD")
//
// With --into it declares the memory too, as Into takes it: for each file
// a package-level array, sized to the whole sectors the drive delivers,
// which mkdisc checks the file fits, and a yaroze.TIM or yaroze.TMD over
// the array for an image or a model:
//
//	cubeTMDData [512]uint32 // 344 bytes
//	cubeTMDFile = disc.Register("ASSETS/CUBE.TMD", "assets/CUBE.TMD").Into(cubeTMDData[:])
//	cubeTMD     = yaroze.TMD(cubeTMDData[:])
//
// Each name is the file's path under the directory, its words run together
// in camel case, then its extension in capitals. With --into, a file that
// changes size needs the command run again, and mkdisc fails the build
// of a disc for one that has outgrown its array.
package discgen

import (
	"bytes"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"unicode"

	"github.com/spf13/cobra"
)

// sectorWords is how many words one 2048-byte sector holds.
const sectorWords = 2048 / 4

// views are the types of package yaroze a file of each extension is read
// as.
var views = map[string]string{
	"TIM": "TIM",
	"TMD": "TMD",
}

// sourceExts are the files the converters read, by extension, which are
// not for the disc.
var sourceExts = map[string]bool{
	"png": true, "bmp": true, "gif": true, "jpg": true, "jpeg": true,
	"obj": true, "mtl": true, "rsd": true, "ply": true, "mat": true,
	"wav": true, "aif": true, "aiff": true, "def": true,
	"mid": true, "midi": true,
}

// An entry is one data file: its path under the directory, with forward
// slashes, and its length in bytes.
type entry struct {
	rel  string
	size int64
}

type options struct {
	Package string // the package the declarations are in
	Dir     string // the directory the files are under, as the program's sources name it
	Root    string // the directory on the disc they are placed under
	Files   string // the name of the slice of every File
	Into    bool   // whether to declare the memory each file is read into
}

// generate writes the declarations for files, which are under opts.Dir.
func generate(opts options, files []entry) ([]byte, error) {
	if len(files) == 0 {
		return nil, fmt.Errorf("%s: no files", opts.Dir)
	}
	type decl struct {
		name, path, src, view string
		words                 int64
		size                  int64
	}
	var decls []decl
	seen := map[string]string{}
	imports := []string{"go.chrisrx.dev/psx/disc"}
	for _, f := range files {
		name, ext := ident(f.rel)
		if prev, ok := seen[name]; ok {
			return nil, fmt.Errorf("%s and %s would both be named %s", prev, f.rel, name)
		}
		seen[name] = f.rel
		view := views[ext]
		if view != "" && !slices.Contains(imports, "go.chrisrx.dev/psx/yaroze") {
			imports = append(imports, "go.chrisrx.dev/psx/yaroze")
		}
		decls = append(decls, decl{
			name:  name,
			path:  path.Join(opts.Root, strings.ToUpper(f.rel)),
			src:   path.Join(filepath.ToSlash(opts.Dir), f.rel),
			view:  view,
			words: max(1, (f.size+2047)/2048) * sectorWords,
			size:  f.size,
		})
	}

	if !opts.Into {
		imports = imports[:1]
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by discgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	fmt.Fprintf(&b, "import (\n")
	for _, imp := range imports {
		fmt.Fprintf(&b, "\t%q\n", imp)
	}
	fmt.Fprintf(&b, ")\n\n")
	file := func(d decl) string { return d.name }
	if opts.Into {
		file = func(d decl) string { return d.name + "File" }
		fmt.Fprintf(&b, "// The files under %s, placed on the disc under %s, each with the memory\n", opts.Dir, opts.Root)
		fmt.Fprintf(&b, "// it is read into: its length rounded up to whole 2048-byte sectors, as\n")
		fmt.Fprintf(&b, "// the drive delivers them.\n")
	} else {
		fmt.Fprintf(&b, "// The files under %s, placed on the disc under %s.\n", opts.Dir, opts.Root)
	}
	fmt.Fprintf(&b, "var (\n")
	for i, d := range decls {
		if !opts.Into {
			fmt.Fprintf(&b, "\t%s = disc.Register(%q, %q)\n", d.name, d.path, d.src)
			continue
		}
		if i > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "\t%sData [%d]uint32 // %d bytes\n", d.name, d.words, d.size)
		fmt.Fprintf(&b, "\t%sFile = disc.Register(%q, %q).Into(%sData[:])\n", d.name, d.path, d.src, d.name)
		if d.view != "" {
			fmt.Fprintf(&b, "\t%s = yaroze.%s(%sData[:])\n", d.name, d.view, d.name)
		}
	}
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// %s is every file above, in the order disc.LoadAll reads them.\n", opts.Files)
	fmt.Fprintf(&b, "var %s = []*disc.File{\n", opts.Files)
	for _, d := range decls {
		fmt.Fprintf(&b, "\t&%s,\n", file(d))
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}

// ident returns the Go name for the file at rel, its directories and base
// name run together in camel case with its extension in capitals after
// them, and the extension, in capitals: "sound/STD0.VH" is soundStd0VH.
func ident(rel string) (name, ext string) {
	ext = strings.ToUpper(strings.TrimPrefix(path.Ext(rel), "."))
	words := strings.FieldsFunc(strings.TrimSuffix(rel, path.Ext(rel)), func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	var b strings.Builder
	for i, w := range words {
		w = strings.ToLower(w)
		if i > 0 {
			w = strings.ToUpper(w[:1]) + w[1:]
		}
		b.WriteString(w)
	}
	name = b.String() + ext
	if name == "" || unicode.IsDigit(rune(name[0])) {
		// A name must start with a letter: "0.VH" is file0VH.
		name = "file" + name
	}
	return name, ext
}

// sources lists the files under dir that the go:generate lines of the Go
// files in pkgDir read: every argument that is a path under dir, other
// than the one after -o or --output. The lines are written as go generate
// runs them, from the package's directory.
func sources(pkgDir, dir string) (map[string]bool, error) {
	names, err := filepath.Glob(filepath.Join(pkgDir, "*.go"))
	if err != nil {
		return nil, err
	}
	dir = path.Clean(filepath.ToSlash(dir))
	out := map[string]bool{}
	for _, name := range names {
		data, err := os.ReadFile(name)
		if err != nil {
			return nil, err
		}
		for _, line := range strings.Split(string(data), "\n") {
			rest, ok := strings.CutPrefix(line, "//go:generate")
			if !ok {
				continue
			}
			words := strings.Fields(rest)
			for i := 0; i < len(words); i++ {
				if words[i] == "-o" || words[i] == "--output" {
					i++
					continue
				}
				w := path.Clean(filepath.ToSlash(words[i]))
				if strings.HasPrefix(w, dir+"/") {
					out[strings.TrimPrefix(w, dir+"/")] = true
				}
			}
		}
	}
	return out, nil
}

// scan lists the files under dir, skipping hidden ones and the sources,
// in lexical order.
func scan(dir string, srcs map[string]bool) ([]entry, error) {
	var files []entry
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if strings.HasPrefix(d.Name(), ".") && p != dir {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if srcs[rel] || sourceExts[strings.ToLower(strings.TrimPrefix(path.Ext(rel), "."))] {
			return nil
		}
		files = append(files, entry{rel: rel, size: info.Size()})
		return nil
	})
	return files, err
}

// Command returns the discgen command, as use.
func Command(use string) *cobra.Command {
	var opts options
	var out string
	cmd := &cobra.Command{
		Use:   use + " [flags] <dir>",
		Short: "write the declarations that put a program's data files on its disc",
		Long: use + ` writes Go declarations for every file under dir: the disc.File
registering it for mkdisc, and a slice of every File for disc.LoadAll, which
reads each into memory it allocates. The sources the converters read are left
out: pictures, models, sounds and scores by their extension, and any file a
go:generate line of the package reads. With --into it declares that memory as
well: an array per file, sized to whole 2048-byte sectors, given to the File
with Into, and a yaroze.TIM or yaroze.TMD over the array for an image or a
model. Run it from the program's package directory, as go:generate does.`,
		Args:         cobra.ExactArgs(1),
		SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			opts.Dir = filepath.ToSlash(filepath.Clean(args[0]))
			if opts.Root == "" {
				opts.Root = strings.ToUpper(path.Base(opts.Dir))
			}
			srcs, err := sources(".", args[0])
			if err != nil {
				return err
			}
			files, err := scan(args[0], srcs)
			if err != nil {
				return err
			}
			src, err := generate(opts, files)
			if err != nil {
				return err
			}
			return os.WriteFile(out, src, 0o644)
		},
	}
	pkg := os.Getenv("GOPACKAGE")
	if pkg == "" {
		pkg = "main"
	}
	f := cmd.Flags()
	f.StringVarP(&out, "output", "o", "zz_generated.disc.go", "the file to write")
	f.StringVarP(&opts.Package, "package", "p", pkg, "the package of the declarations, $GOPACKAGE under go:generate")
	f.StringVar(&opts.Root, "root", "", "the directory on the disc to place the files under, dir in capitals if not given")
	f.StringVar(&opts.Files, "files", "files", "the name of the slice of every File")
	f.BoolVar(&opts.Into, "into", false, "declare an array for each file to be read into, rather than leaving Load to allocate")
	return cmd
}
